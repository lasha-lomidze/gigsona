CREATE FUNCTION assert_projection() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        WITH expected AS (
            SELECT DISTINCT ON (student_id, lesson_date, category)
                student_id, lesson_date, category, id AS change_id, new_aura AS aura
            FROM daily_aura_changes
            ORDER BY student_id, lesson_date, category, id DESC
        )
        (SELECT * FROM expected EXCEPT SELECT * FROM student_aura_scores)
        UNION ALL
        (SELECT * FROM student_aura_scores EXCEPT SELECT * FROM expected)
    ) THEN
        RAISE EXCEPTION 'Current-score projection differs from history';
    END IF;
    IF EXISTS (
        WITH expected AS (
            SELECT s.id AS student_id, COALESCE(SUM(score.aura), 0)::bigint AS total_aura,
                COUNT(DISTINCT score.lesson_date)::integer AS active_days
            FROM students s LEFT JOIN student_aura_scores score ON score.student_id = s.id
            GROUP BY s.id
        ), actual AS (
            SELECT s.id AS student_id, COALESCE(t.total_aura, 0)::bigint AS total_aura,
                COALESCE(t.active_days, 0)::integer AS active_days
            FROM students s LEFT JOIN student_aura_totals t ON t.student_id = s.id
        )
        (SELECT * FROM expected EXCEPT SELECT * FROM actual)
        UNION ALL
        (SELECT * FROM actual EXCEPT SELECT * FROM expected)
    ) THEN
        RAISE EXCEPTION 'Student totals differ from current scores';
    END IF;
END;
$$;

SELECT assert_projection();
DO $$
BEGIN
    IF (SELECT total_aura FROM student_aura_totals WHERE student_id = 1) <> 8
        OR (SELECT active_days FROM student_aura_totals WHERE student_id = 1) <> 1 THEN
        RAISE EXCEPTION 'Backfill did not select the latest cross-group score';
    END IF;
END;
$$;

